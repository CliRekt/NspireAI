struct Message {
    char sender[8];
    char text[128];
};

class NspireAI {
private:
    char prompt_buffer[40] = "";
    Message chat_history[MAX_MESSAGES];
    int msg_count = 0;

    void drawChar(int x, int y, char c, uint16_t color) {
        c = static_cast<char>(std::toupper(c));
        if (c < 32 || c > 90) c = '?';
        int idx = c - 32;
        for (int r = 0; r < 8; r++) {
            uint8_t bits = font8x8[idx][r];
            for (int col = 0; col < 8; col++) {
                if (bits & (0x80 >> col)) {
                    int px = x + col;
                    int py = y + r;
                    if (px >= 0 && px < SCREEN_W && py >= 0 && py < SCREEN_H) {
                        framebuffer[py * SCREEN_W + px] = color;
                    }
                }
            }
        }
    }

    void drawText(int x, int y, const char* str, uint16_t color) {
        while (*str) {
            drawChar(x, y, *str, color);
            x += 8;
            str++;
        }
    }

    void drawRect(int x, int y, int w, int h, uint16_t color) {
        for (int j = y; j < y + h; j++) {
            for (int i = x; i < x + w; i++) {
                if (i >= 0 && i < SCREEN_W && j >= 0 && j < SCREEN_H) {
                    if (i == x || i == x + w - 1 || j == y || j == y + h - 1) {
                        framebuffer[j * SCREEN_W + i] = color;
                    }
                }
            }
        }
    }

    void addMessage(const char* sender, const char* text) {
        if (msg_count >= MAX_MESSAGES) {
            for (int i = 0; i < MAX_MESSAGES - 1; i++) {
                chat_history[i] = chat_history[i + 1];
            }
            msg_count = MAX_MESSAGES - 1;
        }
        strncpy(chat_history[msg_count].sender, sender, 7);
        strncpy(chat_history[msg_count].text, text, 127);
        msg_count++;
    }

    void handleKeyboard() {
        int len = strlen(prompt_buffer);

        for (int k = KEY_NSPIRE_A; k <= KEY_NSPIRE_Z; k++) {
            if (isKeyPressed(static_cast<e_key_index>(k))) {
                if (len < 32) {
                    prompt_buffer[len] = 'A' + (k - KEY_NSPIRE_A);
                    prompt_buffer[len + 1] = '\0';
                    msleep(130);
                    return;
                }
            }
        }

        if (isKeyPressed(KEY_NSPIRE_0) && len < 32) { prompt_buffer[len] = '0'; prompt_buffer[len+1] = '\0'; msleep(130); return; }
        if (isKeyPressed(KEY_NSPIRE_1) && len < 32) { prompt_buffer[len] = '1'; prompt_buffer[len+1] = '\0'; msleep(130); return; }
        if (isKeyPressed(KEY_NSPIRE_2) && len < 32) { prompt_buffer[len] = '2'; prompt_buffer[len+1] = '\0'; msleep(130); return; }
        if (isKeyPressed(KEY_NSPIRE_3) && len < 32) { prompt_buffer[len] = '3'; prompt_buffer[len+1] = '\0'; msleep(130); return; }
        if (isKeyPressed(KEY_NSPIRE_4) && len < 32) { prompt_buffer[len] = '4'; prompt_buffer[len+1] = '\0'; msleep(130); return; }
        if (isKeyPressed(KEY_NSPIRE_5) && len < 32) { prompt_buffer[len] = '5'; prompt_buffer[len+1] = '\0'; msleep(130); return; }
        if (isKeyPressed(KEY_NSPIRE_6) && len < 32) { prompt_buffer[len] = '6'; prompt_buffer[len+1] = '\0'; msleep(130); return; }
        if (isKeyPressed(KEY_NSPIRE_7) && len < 32) { prompt_buffer[len] = '7'; prompt_buffer[len+1] = '\0'; msleep(130); return; }
        if (isKeyPressed(KEY_NSPIRE_8) && len < 32) { prompt_buffer[len] = '8'; prompt_buffer[len+1] = '\0'; msleep(130); return; }
        if (isKeyPressed(KEY_NSPIRE_9) && len < 32) { prompt_buffer[len] = '9'; prompt_buffer[len+1] = '\0'; msleep(130); return; }

        if (isKeyPressed(KEY_NSPIRE_SPACE) && len < 32) { prompt_buffer[len] = ' '; prompt_buffer[len+1] = '\0'; msleep(130); return; }
        if (isKeyPressed(KEY_NSPIRE_PERIOD) && len < 32) { prompt_buffer[len] = '.'; prompt_buffer[len+1] = '\0'; msleep(130); return; }
        if (isKeyPressed(KEY_NSPIRE_MINUS) && len < 32) { prompt_buffer[len] = '-'; prompt_buffer[len+1] = '\0'; msleep(130); return; }

        if (isKeyPressed(KEY_NSPIRE_DEL) && len > 0) {
            prompt_buffer[len - 1] = '\0';
            msleep(130);
            return;
        }

        if (isKeyPressed(KEY_NSPIRE_ENTER) && len > 0) {
            addMessage("YOU", prompt_buffer);

            char ai_reply[128];
            AIBrain::ask(prompt_buffer, ai_reply, sizeof(ai_reply));
            addMessage("AI", ai_reply);

            prompt_buffer[0] = '\0';
            msleep(200);
            return;
        }
    }

public:
    NspireAI() {
        addMessage("AI", "NSPIRE AI ASSISTANT READY.");
        addMessage("AI", "ASK ALG II, PHYSICS OR UNITS!");
    }

    void run() {
        while (true) {
            if (isKeyPressed(KEY_NSPIRE_ESC)) break;

            handleKeyboard();

            memset(framebuffer, 0, sizeof(framebuffer));

            drawText(10, 8, "=== NSPIRE AI ASSISTANT ===", 0x07E0);

            int y_off = 25;
            for (int i = 0; i < msg_count; i++) {
                uint16_t color = (strcmp(chat_history[i].sender, "YOU") == 0) ? 0xFFE0 : 0x07FF;
                char line[140];
                snprintf(line, sizeof(line), "[%s] %s", chat_history[i].sender, chat_history[i].text);
                drawText(10, y_off, line, color);
                y_off += 24;
            }

            drawRect(8, 185, 304, 25, 0xFFE0);
            char display_p[48];
            snprintf(display_p, sizeof(display_p), "> %s_", prompt_buffer);
            drawText(15, 193, display_p, 0xFFFF);

            drawText(10, 222, "[ENTER] SEND  [DEL] ERASE  [ESC] EXIT", 0x7BEF);

            lcd_blit(framebuffer, SCR_320x240_565);
            msleep(20);
        }
    }
};

int main() {
    NspireAI app;
    app.run();
    return 0;
}
